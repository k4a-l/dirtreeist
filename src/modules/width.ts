const includes = (ranges: Range[], code: number): boolean => {
  let low = 0
  let high = ranges.length - 1

  while (low <= high) {
    const middle = Math.floor((low + high) / 2)
    const [start, end] = ranges[middle]
    if (code < start) high = middle - 1
    else if (code > end) low = middle + 1
    else return true
  }

  return false
}

/** East Asian Width が Ambiguous の文字を何幅として数えるか。 */
type AmbiguousWidth = 1 | 2

const charWidth = (code: number, ambiguousWidth: AmbiguousWidth): number => {
  if (code === 0) return 0
  if (code < 0x20 || (code >= 0x7f && code < 0xa0)) return 0 // 制御文字
  if (code < 0x7f) return 1
  if (code >= 0x0300 && code <= 0x036f) return 0 // 結合文字
  if (code === 0x200b || code === 0xfe0f) return 0 // ゼロ幅・異体字セレクタ
  if (includes(wideRanges, code)) return 2
  if (includes(ambiguousRanges, code)) return ambiguousWidth
  return 1
}

/**
 * 等幅表示を前提とした表示幅を返す。
 * 罫線素片や全角スペースを混在させるため、East Asian Width を見て 1/2 を数える。
 */
const stringWidth = (
  text: string,
  ambiguousWidth: AmbiguousWidth
): number => {
  let width = 0
  for (const char of text) {
    width += charWidth(char.codePointAt(0) as number, ambiguousWidth)
  }
  return width
}

/**
 * CJKフォント前提かどうかを、Ambiguousな文字の幅に読み替える。
 * CJKフォントでは罫線素片などが全角で描画されるため2幅として数える。
 */
const ambiguousWidthOf = (cjkFont: OptionsBase['cjkFont']): AmbiguousWidth => {
  return cjkFont ? 2 : 1
}

/**
 * markdown記法のうち、レンダリング後に消える文字を取り除く。
 * keepMarkdown:true のとき、`**bold**` を4文字ではなく8文字と数えてしまうのを防ぐ。
 *
 * あくまで文字数の話であり、太字や色などレンダリング後の字形の違いまでは扱えない。
 */
const stripMarkdown = (text: string): string => {
  return (
    text
      // 画像・リンク: ![alt](src) / [label](href) -> alt / label
      .replace(/!?\[([^\]]*)\]\([^)]*\)/g, '$1')
      // 参照リンク: [label][ref] -> label
      .replace(/!?\[([^\]]*)\]\[[^\]]*\]/g, '$1')
      // コードスパン: `code` -> code
      .replace(/`+([^`]*)`+/g, '$1')
      // 強調: **bold** / *it* / __b__ / _i_ -> 中身
      // 打ち消し(~~)はGFM拡張でパーサが解釈しないため、ここでも除かない
      .replace(/(\*\*\*|\*\*|\*|___|__|_)(.+?)\1/g, '$2')
      // エスケープ: \* -> *
      .replace(/\\([!-/:-@[-`{-~])/g, '$1')
  )
}

